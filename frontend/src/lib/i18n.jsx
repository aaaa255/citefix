const DICTS = { en, zh, es };

/* English unless the visitor picked another language in Settings, which is remembered. */
function initialLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && DICTS[saved]) return saved;
  } catch { /* storage blocked */ }
  return 'en';
}

export function translate(lang, key, params = {}) {
  const entry = DICTS[lang]?.[key] ?? en[key];
  if (entry == null) return key;
  if (typeof entry === 'function') return entry(params);
  return entry.replace(/\{(\w+)\}/g, (match, name) => (params[name] ?? match));
}

const I18nContext = createContext({ lang: 'en', setLang: () => {}, t: (key, params) => translate('en', key, params), list: en.list });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);
  useEffect(() => { document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang; }, [lang]);
  const setLang = useCallback((code) => {
    if (!DICTS[code]) return;
    setLangState(code);
    try { localStorage.setItem(LANG_KEY, code); } catch { /* storage blocked: the choice lasts this visit */ }
  }, []);
  const value = useMemo(() => ({
    lang, setLang, t: (key, params) => translate(lang, key, params), list: DICTS[lang].list,
  }), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
